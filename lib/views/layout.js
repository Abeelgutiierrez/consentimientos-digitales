const { esc } = require('../util');

// Color de texto legible sobre el color de marca.
function inkFor(hex) {
  const m = /^#?([0-9a-f]{6})$/i.exec(hex || '');
  if (!m) return '#ffffff';
  const n = parseInt(m[1], 16);
  const lum = (0.299 * ((n >> 16) & 255) + 0.587 * ((n >> 8) & 255) + 0.114 * (n & 255)) / 255;
  return lum > 0.62 ? '#16161d' : '#ffffff';
}

function safeColor(hex) {
  return /^#[0-9a-f]{6}$/i.test(hex || '') ? hex : '#1f1f2e';
}

function page({ title, body, accent, bodyClass = '', head = '', scripts = '' }) {
  const color = safeColor(accent);
  return `<!doctype html>
<html lang="es">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="theme-color" content="${color}">
<title>${esc(title)}</title>
<link rel="icon" href="data:image/svg+xml,${encodeURIComponent(`<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 32 32'><rect width='32' height='32' rx='8' fill='${color}'/><path d='M9 17l5 5 9-11' stroke='${inkFor(color)}' stroke-width='3.2' fill='none' stroke-linecap='round' stroke-linejoin='round'/></svg>`)}">
<link rel="stylesheet" href="/static/styles.css">
<style>:root{--accent:${color};--accent-ink:${inkFor(color)}}</style>
${head}
</head>
<body class="${esc(bodyClass)}">
${body}
${scripts}
</body>
</html>`;
}

// JSON seguro para incrustar dentro de <script>.
function jsonScript(value) {
  return JSON.stringify(value).replace(/</g, '\\u003c').replace(/[\u2028\u2029]/g, (c) => '\\u' + c.charCodeAt(0).toString(16));
}

